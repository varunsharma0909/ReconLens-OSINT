"""Produce measured offline evaluation results from the eight documented demo fixtures.

This is a *fictional-fixture regression benchmark*, NOT accuracy against real threats.
Predictions and response times are collected from the Flask app during execution,
rather than typed in as invented measurements.

    python tests/build_demo_benchmark.py
    python tests/evaluate_osint.py tests/benchmark_demo_results.csv
"""
from __future__ import annotations

import csv
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app import create_app  # noqa: E402

SCENARIOS = {
    "domain_weak": ("domain", "demo-corp.test"),
    "domain_strong": ("domain", "secure-shop.test"),
    "username_reused": ("username", "demo_analyst"),
    "username_low": ("username", "ghost_user_404"),
    "email_exposed": ("email", "alice@demo-corp.test"),
    "email_clean": ("email", "bob@secure-shop.test"),
    "reputation_flagged": ("reputation", "phish-login.demo-corp.test"),
    "reputation_clean": ("reputation", "secure-shop.test"),
}


def main():
    manifest = ROOT / "tests" / "benchmark_template.csv"
    out = ROOT / "tests" / "benchmark_demo_results.csv"
    with manifest.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))

    if {row["scenario_id"] for row in rows} != set(SCENARIOS):
        raise SystemExit("Benchmark manifest does not match the eight known fictional fixtures.")

    app = create_app({"TESTING": True, "DATABASE_PATH": ":memory:",
                      "SCAN_RATE_LIMIT": "1000 per minute", "ALLOW_LIVE_MODE": True})
    # SQLite :memory: creates a separate database per connection. Use an isolated
    # file instead; no production data or user accounts are accessed.
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        app = create_app({"TESTING": True, "DATABASE_PATH": str(Path(tmp) / "benchmark.db"),
                          "SCAN_RATE_LIMIT": "1000 per minute", "ALLOW_LIVE_MODE": True})
        client = app.test_client()
        results = []
        for row in rows:
            scan_type, target = SCENARIOS[row["scenario_id"]]
            start = time.perf_counter()
            response = client.post(f"/api/scan/{scan_type}",
                                   json={"target": target, "mode": "demo"})
            elapsed_ms = (time.perf_counter() - start) * 1000
            if response.status_code != 201:
                raise SystemExit(f"Demo benchmark scan failed: {row['scenario_id']} "
                                 f"HTTP {response.status_code}")
            scan = response.get_json()["scan"]
            # Predictions are generated by the deployed application's risk score,
            # not copied from the expected labels.
            prediction = int(scan["exposure_score"] > 0)
            results.append({
                "scenario_id": row["scenario_id"],
                "expected_threat": row["expected_threat"],
                "predicted_threat": prediction,
                "response_ms": f"{elapsed_ms:.3f}",
            })
        with out.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=[
                "scenario_id", "expected_threat", "predicted_threat", "response_ms"])
            writer.writeheader()
            writer.writerows(results)
    print(f"Wrote {len(results)} measured *fictional demo* cases to {out}")
    from evaluate_osint import evaluate  # noqa: E402
    evaluate(out)


if __name__ == "__main__":
    main()
