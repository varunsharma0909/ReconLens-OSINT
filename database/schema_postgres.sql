-- ReconLens Phase 2: PostgreSQL schema
-- All timestamps are stored as UTC ISO-8601 text for compatibility with existing reports.
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','analyst')),
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_ci ON users (LOWER(username));
CREATE TABLE IF NOT EXISTS scans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_type TEXT NOT NULL CHECK (scan_type IN ('domain','username','email','reputation')),
  target TEXT NOT NULL,
  mode TEXT NOT NULL CHECK (mode IN ('demo','live')),
  status TEXT NOT NULL,
  exposure_score INTEGER NOT NULL DEFAULT 0,
  exposure_level TEXT NOT NULL DEFAULT 'Low',
  "authorization" TEXT,
  started_at TEXT NOT NULL,
  completed_at TEXT,
  duration_ms INTEGER,
  modules_json TEXT,
  recommendations_json TEXT,
  limitations_json TEXT,
  scoring_json TEXT,
  owner_id BIGINT REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS findings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id BIGINT NOT NULL REFERENCES scans(id) ON DELETE CASCADE,
  module TEXT NOT NULL,
  source TEXT NOT NULL,
  code TEXT NOT NULL,
  title TEXT NOT NULL,
  value TEXT,
  status TEXT NOT NULL CHECK (status IN ('confirmed','not_found','inconclusive','error')),
  severity TEXT NOT NULL CHECK (severity IN ('info','low','medium','high')),
  source_url TEXT,
  collected_at TEXT NOT NULL,
  details_json TEXT
);
CREATE TABLE IF NOT EXISTS audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  resource TEXT,
  created_at TEXT NOT NULL,
  remote_ip TEXT
);
CREATE INDEX IF NOT EXISTS idx_findings_scan ON findings(scan_id);
CREATE INDEX IF NOT EXISTS idx_scans_started ON scans(started_at);
CREATE INDEX IF NOT EXISTS idx_scans_owner ON scans(owner_id, id);
CREATE INDEX IF NOT EXISTS idx_audit_time ON audit_events(created_at);
